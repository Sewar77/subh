const localeFor = (language) =>
  language === "ar" ? "ar-JO-u-nu-arab" : "en-US";

export const getBookRequestCopy = (language) => copy[language] || copy.en;

export const formatRequestNumber = (value, language) =>
  new Intl.NumberFormat(localeFor(language)).format(Number(value || 0));

export const formatRequestMoney = (value, currency, language) => {
  if (value === null || value === undefined) return "—";
  return new Intl.NumberFormat(localeFor(language), {
    style: "currency",
    currency: currency || "USD",
    minimumFractionDigits: 2,
  }).format(Number(value));
};

export const formatRequestDate = (value, language, withTime = false) => {
  if (!value) return "—";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(localeFor(language), {
    dateStyle: "medium",
    ...(withTime ? { timeStyle: "short" } : {}),
  }).format(date);
};

export const getRequestStatusLabel = (value, language) =>
  getBookRequestCopy(language).statusLabels[value] || "—";
